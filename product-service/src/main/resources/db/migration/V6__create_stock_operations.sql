CREATE TABLE stock_operations (
                                  id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                  idempotency_key VARCHAR(128) NOT NULL,
                                  book_id         BIGINT       NOT NULL,
                                  operation_type  VARCHAR(20)  NOT NULL,
                                  amount          INTEGER      NOT NULL,
                                  created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
                                  CONSTRAINT pk_stock_operations PRIMARY KEY (id),
                                  CONSTRAINT uc_stock_operations_idempotency_key UNIQUE (idempotency_key),
                                  CONSTRAINT chk_stock_operations_type CHECK (operation_type IN ('DECREASE', 'INCREASE')),
                                  CONSTRAINT chk_stock_operations_amount CHECK (amount > 0),
                                  CONSTRAINT fk_stock_operations_on_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE
);